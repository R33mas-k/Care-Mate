    private void btnEditPatientActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditPatientActionPerformed
        // TODO add your handling code here:
    // 1. قراءة اسم المريض
    String name = jTextField1.getText().trim();

    // 2. قراءة الجندر من Radio Buttons
    String gender = "";
    if (rbtnMale.isSelected()) {
        gender = "Male";
    } else if (rbtnFemale.isSelected()) {
        gender = "Female";
    }

    // 3. قراءة فصيلة الدم من ComboBox
    String bloodType = ComboBloodType.getSelectedItem().toString();

    // 4. قراءة العنوان من TextField
    String address = txtAddress.getText().trim();

    // 5. التحقق من الإدخالات
    if (name.isEmpty() || gender.isEmpty() || bloodType.isEmpty() || address.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill all fields correctly", "Missing Information", JOptionPane.WARNING_MESSAGE);
    } else {
        // 6. عرض المعلومات بعد التعديل
        String message = "Patient Details:\n"
                       + "Name: " + name + "\n"
                       + "Gender: " + gender + "\n"
                       + "Blood Type: " + bloodType + "\n"
                       + "Address: " + address;

        JOptionPane.showMessageDialog(this, message, "Edited Details", JOptionPane.INFORMATION_MESSAGE);
    }


       

    }//GEN-LAST:event_btnEditPatientActionPerformed

